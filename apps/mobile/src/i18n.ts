export const LANG: Lang = (navigator.language || 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en';
export const LOCALE = LANG === 'pt' ? 'pt-PT' : 'en-GB';
const MESSAGES: Record<'pt' | 'en', Record<Key, string>> = { pt, en };

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = MESSAGES[LANG === 'pt' ? 'pt' : 'en'][key] ?? pt[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const num = (v: number, decimals = 1) => v.toLocaleString(LOCALE, { maximumFractionDigits: decimals, minimumFractionDigits: 0 });
export const clock = (ms: number) => new Date(ms).toLocaleTimeString(LOCALE, { hour: '2-digit', minute: '2-digit', second: '2-digit' });
export const mmss = (s: number) => {
  const v = Math.max(0, s);
  return `${Math.floor(v / 60)}:${String(Math.floor(v % 60)).padStart(2, '0')}`;
};
