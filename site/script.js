/* ==========================================================================
   telemeSYNC landing page: navigation, demo video, supporters, visit counter
   ========================================================================== */

// Site settings: edit here only.
const SITE_CONFIG = {
  // Latest release (version and download link), also read by the program to announce updates.
  latestUrl: 'data/latest.json',
  // YouTube video ID of the demo (the part after "watch?v="). Empty = "em breve" placeholder.
  youtubeId: 'zG_BmoFqpx0',
  // GoatCounter site code (https://<code>.goatcounter.com). Empty = no counting and no counter shown.
  goatcounterCode: 'telemesync',
  // Supporters list generated by the GitHub Action from the Buy Me a Coffee API.
  supportersUrl: 'data/supporters.json',
  // How many supporters to list.
  supportersMax: 8,
};

document.addEventListener('DOMContentLoaded', () => {
  initNav();
  initVersion();
  initVideo();
  loadSupporters();
  initVisitCounter();
  initReveal();
});

// Opens/closes the mobile menu and closes it after a link is chosen
function initNav() {
  const toggle = document.querySelector('.nav-toggle');
  const nav = document.getElementById('menu');
  if (!toggle || !nav) return;
  const setOpen = (open) => {
    nav.classList.toggle('is-open', open);
    toggle.setAttribute('aria-expanded', String(open));
    toggle.setAttribute('aria-label', open ? 'Fechar menu' : 'Abrir menu');
  };
  toggle.addEventListener('click', () => setOpen(!nav.classList.contains('is-open')));
  nav.addEventListener('click', (e) => {
    if (e.target.closest('a')) setOpen(false);
  });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') setOpen(false);
  });
}

// Writes the latest version and download link (data/latest.json) into the download buttons
function initVersion() {
  fetch(SITE_CONFIG.latestUrl, { cache: 'no-cache' })
    .then((r) => (r.ok ? r.json() : Promise.reject(r.status)))
    .then((latest) => {
      if (latest.version) document.querySelectorAll('.js-version').forEach((el) => (el.textContent = latest.version));
      if (latest.downloadUrl) document.querySelectorAll('.js-download').forEach((el) => (el.href = latest.downloadUrl));
    })
    .catch(() => {
      /* keep the version and link written in the HTML */
    });
}

// Shows the demo video only after a click (no YouTube request before that, privacy-enhanced domain)
function initVideo() {
  const box = document.querySelector('.js-video');
  const button = box?.querySelector('.video__play');
  const label = box?.querySelector('.js-video-label');
  if (!box || !button) return;
  const id = SITE_CONFIG.youtubeId.trim();
  if (!id) {
    button.disabled = true;
    return;
  }
  if (label) label.textContent = 'Ver a demonstração';
  const poster = box.querySelector('.js-video-poster');
  if (poster) loadPoster(poster, id);
  button.addEventListener('click', () => {
    const iframe = document.createElement('iframe');
    iframe.src = `https://www.youtube-nocookie.com/embed/${encodeURIComponent(id)}?autoplay=1&rel=0`;
    iframe.title = 'Demonstração do telemeSYNC';
    iframe.allow = 'accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture';
    iframe.allowFullscreen = true;
    box.replaceChildren(iframe);
  });
}

// Shows the video's YouTube thumbnail behind the play button (the illustration stays if it fails)
function loadPoster(img, id) {
  const base = `https://i.ytimg.com/vi/${encodeURIComponent(id)}`;
  img.addEventListener('load', () => {
    // Without an HD thumbnail YouTube answers with a 120px grey placeholder: use the smaller one
    if (img.naturalWidth <= 120 && img.src.includes('maxresdefault')) {
      img.src = `${base}/hqdefault.jpg`;
      return;
    }
    img.hidden = false;
  });
  img.src = `${base}/maxresdefault.jpg`;
}

// Fetches the latest Buy Me a Coffee supporters (JSON built by the GitHub Action) and lists them
async function loadSupporters() {
  const list = document.querySelector('.js-supporters');
  if (!list) return;
  let supporters = [];
  try {
    const res = await fetch(SITE_CONFIG.supportersUrl, { cache: 'no-cache' });
    if (res.ok) supporters = (await res.json()).supporters ?? [];
  } catch {
    supporters = [];
  }
  list.replaceChildren();
  if (!supporters.length) {
    list.append(createEmptySupporter());
    return;
  }
  supporters.slice(0, SITE_CONFIG.supportersMax).forEach((s) => list.append(createSupporterItem(s)));
}

// Builds one supporter row: cup, name, coffees and how long ago
function createSupporterItem(s) {
  const li = document.createElement('li');
  li.className = 'supporter';
  const cup = document.createElement('span');
  cup.className = 'supporter__cup';
  cup.setAttribute('aria-hidden', 'true');
  cup.textContent = '☕';
  const text = document.createElement('div');
  const name = document.createElement('div');
  name.className = 'supporter__name';
  name.textContent = s.name || 'Alguém';
  const meta = document.createElement('div');
  meta.className = 'supporter__meta';
  const coffees = Number(s.coffees) || 1;
  meta.textContent = `${coffees} ${coffees === 1 ? 'café' : 'cafés'}${s.date ? ` · ${timeAgo(s.date)}` : ''}`;
  text.append(name, meta);
  li.append(cup, text);
  return li;
}

// Message shown while there are no supporters yet
function createEmptySupporter() {
  const li = document.createElement('li');
  li.className = 'supporters__empty';
  li.textContent = 'Ainda sem apoiantes. Seja o primeiro!';
  return li;
}

// Turns an ISO date into "há 3 dias" style text in Portuguese
function timeAgo(iso) {
  const then = new Date(iso);
  if (Number.isNaN(then.getTime())) return '';
  const rtf = new Intl.RelativeTimeFormat('pt-PT', { numeric: 'auto' });
  const seconds = (then.getTime() - Date.now()) / 1000;
  const units = [
    ['year', 31536000],
    ['month', 2592000],
    ['week', 604800],
    ['day', 86400],
    ['hour', 3600],
    ['minute', 60],
  ];
  for (const [unit, size] of units) {
    if (Math.abs(seconds) >= size) return rtf.format(Math.round(seconds / size), unit);
  }
  return 'agora mesmo';
}

// Counts the visit with GoatCounter (no cookies) and shows the total visits to the site (footer and sponsors card)
function initVisitCounter() {
  const code = SITE_CONFIG.goatcounterCode.trim();
  const boxes = document.querySelectorAll('.js-visits');
  if (!code) return;
  const endpoint = `https://${code}.goatcounter.com`;
  const script = document.createElement('script');
  script.async = true;
  script.src = 'https://gc.zgo.at/count.js';
  script.dataset.goatcounter = `${endpoint}/count`;
  document.head.append(script);
  // Pages without the counter box (e.g. legal.html) are still counted
  if (!boxes.length) return;
  // Whole-site total; needs "Allow adding visitor counts on your website" in GoatCounter's settings.
  // GoatCounter answers 404 until its first visits are processed: the counter stays hidden until then.
  fetch(`${endpoint}/counter/TOTAL.json`)
    .then((r) => (r.ok ? r.json() : Promise.reject(r.status)))
    .then((d) => {
      // The count comes formatted in English ("1,234"): show it the Portuguese way ("1234" / "12 345")
      const n = Number(String(d.count).replace(/\D/g, ''));
      boxes.forEach((box) => {
        const out = box.querySelector('.js-visits-count');
        if (out) out.textContent = n.toLocaleString('pt-PT');
        box.hidden = false;
      });
    })
    .catch(() => {
      /* counter unavailable: keep it hidden */
    });
}

// Fades sections in as they scroll into view
function initReveal() {
  const items = document.querySelectorAll('.section .container > *');
  if (!('IntersectionObserver' in window)) return;
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) {
          e.target.classList.add('is-visible');
          io.unobserve(e.target);
        }
      });
    },
    { rootMargin: '0px 0px -10% 0px' },
  );
  items.forEach((el) => {
    el.classList.add('reveal');
    io.observe(el);
  });
}
